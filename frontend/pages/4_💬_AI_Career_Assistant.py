import streamlit as st
from components.ui_theme import inject_custom_theme, render_html
from components.sidebar import render_sidebar
from utils.api_client import api

st.set_page_config(page_title="Career Assistant — CareerPilot", page_icon="🧭", layout="wide")
inject_custom_theme()
render_sidebar()

candidate = st.session_state.get("candidate")
candidate_id = st.session_state.get("candidate_id")

if not candidate:
    st.warning("Please select or initialize an active candidate in the sidebar.")
    st.stop()

# Header
st.title("AI Career Assistant")
st.markdown("Your autonomous career agent. Inquire about opportunities, benchmark your skills, save jobs, or trigger interview prep workflows.")

# Initialize Chat State
if "chat_messages" not in st.session_state:
    st.session_state["chat_messages"] = []
    history = api.get_chat_history(candidate_id)
    if history and history.get("messages"):
        for m in history["messages"]:
            st.session_state["chat_messages"].append({
                "role": "user" if m.get("sender") == "user" else "assistant",
                "content": m.get("content", ""),
                "tool_calls": []
            })
    else:
        st.session_state["chat_messages"].append({
            "role": "assistant",
            "content": f"Hi {candidate.get('full_name').split()[0]}, I am your career copilot. How can I assist you today? You can ask me to search for roles, check missing skills for any job, save opportunities, or generate customized interview preparation.",
            "tool_calls": [],
            "source": "assistant"
        })

# Suggested Action Chips
render_html("<div style='font-size: 0.8rem; font-weight: 700; text-transform: uppercase; color: #64748B; margin-bottom: 0.4rem;'>Suggested Inquiries</div>")
p1, p2, p3, p4 = st.columns(4)

with p1:
    if st.button("Find remote AI internships", use_container_width=True):
        st.session_state["pending_prompt"] = "Find me suitable AI Engineer internships. I know Python, SQL, Machine Learning and n8n. I prefer remote opportunities."
with p2:
    if st.button("Show my saved jobs", use_container_width=True):
        st.session_state["pending_prompt"] = "Show my saved jobs."
with p3:
    if st.button("Missing skills for job_001?", use_container_width=True):
        st.session_state["pending_prompt"] = "What skills am I missing for job_001?"
with p4:
    if st.button("Prep interview for job_001", use_container_width=True):
        st.session_state["pending_prompt"] = "Prepare interview questions for job_001."

st.markdown("<div style='height: 10px;'></div>", unsafe_allow_html=True)

# Conversation Stream
for msg in st.session_state["chat_messages"]:
    role = msg.get("role", "assistant")
    with st.chat_message(role):
        st.markdown(msg.get("content", ""))
        
        tool_calls = msg.get("tool_calls", [])
        if tool_calls:
            with st.expander(f"Tool Execution Trace ({len(tool_calls)} action{'s' if len(tool_calls) > 1 else ''})", expanded=False):
                for tc in tool_calls:
                    t_name = tc.get("tool_name", "tool")
                    args = tc.get("arguments", {})
                    success = tc.get("success", True)
                    status_badge = "Success" if success else "Failed"
                    st.markdown(f"**Action:** `{t_name}` · **Status:** `{status_badge}`")
                    st.json(args)
        
        source = msg.get("source")
        if source == "ollama":
            st.caption("Generated by Local Ollama (llama3.2:3b)")
        elif source == "fallback":
            st.caption("Executed via Offline Deterministic Engine")

# Chat Input Handling
user_prompt = st.chat_input("Type your question or career command...")

if "pending_prompt" in st.session_state and st.session_state["pending_prompt"]:
    user_prompt = st.session_state.pop("pending_prompt")

if user_prompt:
    st.session_state["chat_messages"].append({"role": "user", "content": user_prompt})
    with st.chat_message("user"):
        st.markdown(user_prompt)

    with st.chat_message("assistant"):
        with st.spinner("Analyzing request and executing tools..."):
            response = api.send_chat_message(candidate_id, user_prompt)
            assistant_reply = response.get("message", "Error processing request.")
            tool_calls = response.get("tool_calls", [])
            source = response.get("source", "assistant")

            st.markdown(assistant_reply)

            if tool_calls:
                with st.expander(f"Tool Execution Trace ({len(tool_calls)} action{'s' if len(tool_calls) > 1 else ''})", expanded=False):
                    for tc in tool_calls:
                        t_name = tc.get("tool_name", "tool")
                        args = tc.get("arguments", {})
                        success = tc.get("success", True)
                        status_badge = "Success" if success else "Failed"
                        st.markdown(f"**Action:** `{t_name}` · **Status:** `{status_badge}`")
                        st.json(args)

            if source == "ollama":
                st.caption("Generated by Local Ollama (llama3.2:3b)")
            elif source == "fallback":
                st.caption("Executed via Offline Deterministic Engine")

            st.session_state["chat_messages"].append({
                "role": "assistant",
                "content": assistant_reply,
                "tool_calls": tool_calls,
                "source": source
            })
    st.rerun()

st.sidebar.divider()
if st.sidebar.button("Clear Conversation History", use_container_width=True):
    st.session_state["chat_messages"] = []
    st.rerun()
